// LiveKit as a supervised child process (docs/SPEC-SERVER-CLI.md C3, §4).
//
// Public API (small on purpose):
//   liveKitYaml(opts)        → the LiveKit config file contents (generated on every start)
//   locateLiveKit()          → path of the livekit-server(.exe) binary to run
//   superviseLiveKit(opts)   → spawn it, restart on crashes, { ready, stop() }
import { spawn, spawnSync, type ChildProcess } from 'node:child_process'
import { existsSync, realpathSync } from 'node:fs'
import { connect, isIP } from 'node:net'
import path from 'node:path'
import { createInterface } from 'node:readline'
import { isSea } from 'node:sea'

// ---------- config ----------

export interface LiveKitYamlOptions {
  apiKey: string
  /** LiveKit rejects secrets shorter than 32 characters. */
  apiSecret: string
  /**
   * Interfaces for the signaling port (and, when they are specific IPs, for media too: see below).
   * `['0.0.0.0']` = all interfaces (the repo's livekit.yaml).
   */
  bindAddresses: string[]
  /** Signaling (http/ws) TCP port. Default setup: 7880. */
  port: number
  /**
   * ICE/TCP fallback port (7881). 0 disables ICE/TCP. Note: LiveKit always listens on this port on
   * all interfaces, whatever `bindAddresses` says, so a loopback-only setup should pass 0.
   */
  tcpPort: number
  /** Single UDP port for all media (7882). */
  udpPort: number
  /** IP advertised to clients as an ICE candidate (e.g. the Tailscale 100.x IP). Empty = auto. */
  nodeIp?: string
  /** Discover the public IP via STUN and advertise it (public/port-forwarded hosts). */
  useExternalIp: boolean
  /** With `nodeIp` / external IP: also advertise the machine's own interface IPs. Default true. */
  advertiseInternalIp?: boolean
}

const WILDCARDS = new Set(['0.0.0.0', '::', ''])
const isLoopback = (ip: string) => ip === '::1' || ip.startsWith('127.')

/** YAML-safe scalar: JSON strings are valid YAML double-quoted strings. */
const q = (s: string) => JSON.stringify(s)

/**
 * LiveKit config mirroring the repo's livekit.yaml (same room/logging settings), but self-contained:
 * keys go in the `keys:` map instead of $LIVEKIT_KEYS and the node IP in `rtc.node_ip` instead of $NODE_IP.
 *
 * When `bindAddresses` are all specific IPs (no 0.0.0.0 / ::), the UDP media port is restricted to those
 * IPs too (`rtc.ips.includes`), and loopback candidates are enabled if one of them is loopback. That makes
 * `bindAddresses: ['127.0.0.1']` + `tcpPort: 0` a fully loopback-only LiveKit (no firewall prompt).
 */
export function liveKitYaml(opts: LiveKitYamlOptions): string {
  if (opts.bindAddresses.length === 0) throw new Error('liveKitYaml: bindAddresses is empty')
  if (opts.apiKey.trim() === '' || /[\r\n]/.test(opts.apiKey + opts.apiSecret)) throw new Error('liveKitYaml: bad API key/secret')
  for (const [name, port] of [['port', opts.port], ['tcpPort', opts.tcpPort], ['udpPort', opts.udpPort]] as const) {
    if (!Number.isInteger(port) || port < 0 || port > 65535 || (port === 0 && name !== 'tcpPort')) {
      throw new Error(`liveKitYaml: invalid ${name} ${port}`)
    }
  }
  const specific = opts.bindAddresses.every((a) => !WILDCARDS.has(a.trim()))
  if (specific) {
    for (const a of opts.bindAddresses) if (!isIP(a)) throw new Error(`liveKitYaml: bind address "${a}" is not an IP`)
  }
  const lines = [
    '# Generated by nexo-server on every start. Edits are overwritten; change the Nexo Server config instead.',
    `port: ${opts.port}`,
    'bind_addresses:',
    ...opts.bindAddresses.map((a) => `  - ${q(a)}`),
    'rtc:',
    `  tcp_port: ${opts.tcpPort}`,
    `  udp_port: ${opts.udpPort}`,
    `  use_external_ip: ${opts.useExternalIp}`,
  ]
  if (opts.nodeIp) lines.push(`  node_ip: ${q(opts.nodeIp)}`)
  lines.push(`  advertise_internal_ip: ${opts.advertiseInternalIp ?? true}`)
  if (specific) {
    lines.push('  ips:', '    includes:')
    for (const a of opts.bindAddresses) lines.push(`      - ${q(`${a}/${isIP(a) === 6 ? 128 : 32}`)}`)
    if (opts.bindAddresses.some(isLoopback)) lines.push('  enable_loopback_candidate: true')
  }
  lines.push(
    'room:',
    '  empty_timeout: 60',
    '  max_participants: 25',
    'logging:',
    '  level: info',
    'keys:',
    `  ${q(opts.apiKey)}: ${q(opts.apiSecret)}`,
    '',
  )
  return lines.join('\n')
}

// ---------- binary ----------

const EXE = process.platform === 'win32' ? 'livekit-server.exe' : 'livekit-server'
const PLATFORM_DIR = `${process.platform === 'win32' ? 'win' : process.platform}-${process.arch}`

/**
 * Path of the LiveKit binary:
 *  1. `NEXO_LIVEKIT_BIN` (env override),
 *  2. as a single executable: next to nexo-server(.exe) (the release zip layout),
 *  3. in dev: next to the running script, or `server-cli/dist/<platform>/` (where `npm run build:win` puts it).
 * Throws with the list of places it looked.
 */
export function locateLiveKit(env: NodeJS.ProcessEnv = process.env): string {
  if (env.NEXO_LIVEKIT_BIN) {
    if (!existsSync(env.NEXO_LIVEKIT_BIN)) throw new Error(`NEXO_LIVEKIT_BIN points to a missing file: ${env.NEXO_LIVEKIT_BIN}`)
    return env.NEXO_LIVEKIT_BIN
  }
  const candidates: string[] = []
  if (isSea()) {
    candidates.push(path.join(path.dirname(process.execPath), EXE))
  } else if (process.argv[1]) {
    // `node src/main.ts` → server-cli/src;  `node dist/nexo-server.cjs` → server-cli/dist
    const scriptDir = path.dirname(realpathSync(process.argv[1]))
    candidates.push(
      path.join(scriptDir, EXE),
      path.join(scriptDir, PLATFORM_DIR, EXE),
      path.join(scriptDir, '..', 'dist', PLATFORM_DIR, EXE),
    )
  }
  const found = candidates.find((c) => existsSync(c))
  if (found) return found
  throw new Error(`LiveKit binary (${EXE}) not found. Looked in:\n  ${candidates.join('\n  ')}\nSet NEXO_LIVEKIT_BIN to its path.`)
}

// ---------- supervision ----------

export interface SuperviseOptions {
  binary: string
  configPath: string
  /** Receives LiveKit's output lines (prefixed `[livekit]`) and supervisor messages. */
  log: (line: string) => void
  /** Called once when LiveKit keeps crashing (or can't be started) and the supervisor gives up. */
  onFatal: (err: Error) => void
  /** Signaling port probed for readiness. Default 7880. */
  port?: number
  /** Address the readiness probe connects to. Default 127.0.0.1. */
  host?: string
  /** Give up after this many unexpected exits within `crashWindowMs`. Default 5 in 60 s. */
  maxCrashes?: number
  crashWindowMs?: number
  /** `ready` rejects if the signaling port doesn't accept connections in time. Default 20 s. */
  readyTimeoutMs?: number
}

export interface LiveKitProcess {
  /** Resolves when the first LiveKit process accepts connections on its signaling port. */
  ready: Promise<void>
  /** Stops LiveKit (and stops restarting it). Safe to call more than once. */
  stop(): Promise<void>
}

/** Harmless LiveKit messages hidden from the console (with the Go stack trace that follows them). */
const QUIET = [/CPU monitoring unsupported/] // every start on Windows: no capacity management there
/** LiveKit's log lines start with a timestamp; stack trace lines don't. */
const LOG_START = /^\d{4}-\d\d-\d\dT/

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms))

function canConnect(host: string, port: number): Promise<boolean> {
  return new Promise((resolve) => {
    const socket = connect({ host, port })
    const done = (ok: boolean) => {
      socket.destroy()
      resolve(ok)
    }
    socket.setTimeout(1000, () => done(false))
    socket.once('connect', () => done(true))
    socket.once('error', () => done(false))
  })
}

/** Is something already accepting connections on host:port? (Connect-based: no listen, no firewall prompt.) */
export const portInUse = canConnect

/**
 * Runs `<binary> --config <configPath>` and keeps it running.
 *
 * - Output goes to `log`, one line at a time, prefixed `[livekit]`.
 * - An unexpected exit is restarted with exponential backoff (0.5 s … 10 s). After `maxCrashes` exits within
 *   `crashWindowMs` (or if the binary can't be spawned at all) it stops trying and calls `onFatal`.
 * - Orphans: on Windows, Node (libuv) puts non-detached children in a job object that kills them when this
 *   process dies, even if it is killed hard. `stop()` terminates LiveKit (TerminateProcess; Windows has no
 *   SIGTERM) and falls back to `taskkill /T /F` on the PID tree. Elsewhere: SIGTERM, then SIGKILL after 5 s.
 * - Ctrl+C in a Windows console also reaches LiveKit directly (same console); call `stop()` first thing in
 *   the signal handler so that exit isn't treated as a crash.
 */
export function superviseLiveKit(opts: SuperviseOptions): LiveKitProcess {
  const port = opts.port ?? 7880
  const host = opts.host ?? '127.0.0.1'
  const maxCrashes = opts.maxCrashes ?? 5
  const crashWindowMs = opts.crashWindowMs ?? 60_000
  const readyTimeoutMs = opts.readyTimeoutMs ?? 20_000
  const log = (line: string) => opts.log(`[livekit] ${line}`)

  let child: ChildProcess | null = null
  let stopping = false
  let fatal = false
  let restartTimer: NodeJS.Timeout | null = null
  const crashes: number[] = []

  let resolveReady!: () => void
  let rejectReady!: (err: Error) => void
  let readySettled = false
  const ready = new Promise<void>((res, rej) => {
    resolveReady = () => {
      readySettled = true
      res()
    }
    rejectReady = (err) => {
      readySettled = true
      rej(err)
    }
  })
  ready.catch(() => {}) // callers may not await it; failures are reported through onFatal too

  function giveUp(err: Error) {
    if (fatal || stopping) return
    fatal = true
    log(err.message)
    if (!readySettled) rejectReady(err)
    opts.onFatal(err)
  }

  function spawnOnce() {
    if (stopping || fatal) return
    let proc: ChildProcess
    try {
      proc = spawn(opts.binary, ['--config', opts.configPath], {
        stdio: ['ignore', 'pipe', 'pipe'],
        windowsHide: true,
      })
    } catch (err) {
      giveUp(new Error(`could not start ${opts.binary}: ${(err as Error).message}`))
      return
    }
    child = proc
    for (const stream of [proc.stdout, proc.stderr]) {
      if (!stream) continue
      let skipStack = false
      createInterface({ input: stream, crlfDelay: Infinity }).on('line', (line) => {
        if (!line) return
        if (QUIET.some((re) => re.test(line))) {
          skipStack = true
          return
        }
        if (skipStack && !LOG_START.test(line)) return // its stack trace
        skipStack = false
        log(line)
      })
    }
    proc.once('error', (err) => {
      // Spawn failure (ENOENT, EACCES…): retrying won't help.
      if (proc.pid === undefined) giveUp(new Error(`could not start ${opts.binary}: ${err.message}`))
    })
    proc.once('exit', (code, signal) => {
      if (child === proc) child = null
      if (stopping || fatal || proc.pid === undefined) return
      const now = Date.now()
      crashes.push(now)
      while (crashes.length && now - crashes[0]! > crashWindowMs) crashes.shift()
      const why = signal ? `signal ${signal}` : `code ${code}`
      if (crashes.length >= maxCrashes) {
        giveUp(new Error(`LiveKit exited ${crashes.length} times in ${Math.round(crashWindowMs / 1000)} s (last: ${why}); giving up`))
        return
      }
      const delay = Math.min(500 * 2 ** (crashes.length - 1), 10_000)
      log(`exited unexpectedly (${why}); restarting in ${delay} ms`)
      restartTimer = setTimeout(() => {
        restartTimer = null
        spawnOnce()
      }, delay)
    })
  }

  async function waitReady() {
    const deadline = Date.now() + readyTimeoutMs
    while (!stopping && !fatal && Date.now() < deadline) {
      // Only count it when our own child is alive: the port might belong to someone else.
      if (child && child.exitCode === null && (await canConnect(host, port))) {
        if (child && child.exitCode === null) return resolveReady()
      }
      await sleep(200)
    }
    if (!readySettled) {
      rejectReady(new Error(stopping ? 'LiveKit stopped before it was ready' : `LiveKit did not accept connections on ${host}:${port} within ${readyTimeoutMs / 1000} s`))
    }
  }

  async function stop() {
    stopping = true
    if (restartTimer) clearTimeout(restartTimer)
    restartTimer = null
    if (!readySettled) rejectReady(new Error('LiveKit stopped before it was ready'))
    const proc = child
    if (!proc || proc.exitCode !== null || proc.signalCode !== null) return
    const exited = new Promise<void>((r) => proc.once('exit', () => r()))
    const waitExit = (ms: number) => Promise.race([exited.then(() => true), sleep(ms).then(() => false)])
    if (process.platform === 'win32') {
      proc.kill() // TerminateProcess
      if (!(await waitExit(3000)) && proc.pid) {
        spawnSync('taskkill', ['/pid', String(proc.pid), '/T', '/F'], { windowsHide: true, stdio: 'ignore' })
        await waitExit(3000)
      }
    } else {
      proc.kill('SIGTERM')
      if (!(await waitExit(5000))) {
        proc.kill('SIGKILL')
        await waitExit(3000)
      }
    }
  }

  spawnOnce()
  void waitReady()
  return { ready, stop }
}
